import { useMemo } from 'react'
import { daylightByLatitude } from '@malevo/model'
import type { BodyInfoDto, CalendarInfo, SystemInfoDto } from '../../../../shared/types'
import { DateInput } from '../../components/DateInput'
import { NumberField, TextField, duration, sig } from '../../components/fields'
import { useFormattedOne } from '../../state'

const CLASSES = [
  ['rocky', 'Rocky'],
  ['ocean', 'Ocean world'],
  ['ice-giant', 'Ice giant'],
  ['gas-giant', 'Gas giant'],
  ['dwarf', 'Dwarf'],
  ['belt', 'Belt']
] as const

type Value = Record<string, unknown> & {
  name: string
  parent?: string
  class: string
  orbit: Record<string, unknown> & {
    a_au?: number
    a_km?: number
    e: number
    i_deg: number
    node_deg: number
    peri_deg: number
    meanAnomaly_deg: number
    epoch: { t_s: number; cal?: string; text?: string }
  }
  mass_mearth: number
  radius_km: number
  rotation: { period_h?: number; locked?: boolean; tilt_deg: number; equinox_deg?: number; meridian_deg?: number }
  albedo?: number
  atmosphere?: { pressure_atm: number; scaleHeight_km?: number }
  lock?: { gen: string }
}

interface Props {
  body: BodyInfoDto
  system: SystemInfoDto
  calendars: CalendarInfo[]
  displayCal: string
  version: number
  onDeleted(): void
}

/** Edit one body: what it is, its orbit, its spin; and what follows from them. Every change is unsaved until Save. */
export function BodyEditor({ body, system, calendars, displayCal, version, onDeleted }: Props): React.JSX.Element {
  const v = body.value as Value
  const save = (patch: Partial<Value>): void => {
    const next: Value = { ...v, ...patch }
    // Editing a generated body makes it the author's: it is no longer the generator's output.
    delete next.lock
    void window.malevo.world.setEntity('body', body.id, next)
  }
  const setOrbit = (patch: Partial<Value['orbit']>): void => save({ orbit: { ...v.orbit, ...patch } })
  const setRotation = (patch: Partial<Value['rotation']>): void => {
    const r = { ...v.rotation, ...patch }
    if (r.locked) delete r.period_h
    else delete r.locked
    save({ rotation: r })
  }
  const inKm = v.orbit.a_km !== undefined
  const parents = system.bodies.filter((b) => b.id !== body.id && !isDescendant(system, b.id, body.id))
  const moons = system.bodies.filter((b) => b.parent === body.id)
  const epochText = useFormattedOne(displayCal, v.orbit.epoch.t_s, 'minute', version)
  const daylight = useMemo(() => daylightByLatitude(body.tilt, 15), [body.tilt])
  const day = body.solarDay

  const remove = (): void => {
    const msg = moons.length
      ? `Delete “${v.name}”?\n\nIts moons will be left without a parent:\n${moons.map((m) => `• ${m.name}`).join('\n')}`
      : `Delete “${v.name}”?`
    if (window.confirm(msg)) void window.malevo.world.deleteEntity('body', body.id).then(onDeleted)
  }

  return (
    <div className="body-editor" data-editing={body.id}>
      <div className="field-row">
        <TextField label="Name" value={v.name} onCommit={(name) => name.trim() && save({ name: name.trim() })} id="bodyName" />
        <label className="field">
          Kind
          <select value={v.class} onChange={(e) => save({ class: e.target.value })}>
            {CLASSES.map(([k, l]) => (
              <option key={k} value={k}>
                {l}
              </option>
            ))}
          </select>
        </label>
        <label className="field">
          Orbits
          <select value={v.parent ?? ''} onChange={(e) => save({ parent: e.target.value || undefined })}>
            <option value="">{system.star?.name ?? 'the star'}</option>
            {parents.map((p) => (
              <option key={p.id} value={p.id}>
                {p.name}
              </option>
            ))}
          </select>
        </label>
      </div>
      {v.lock && (
        <p className="muted small">Generated by {v.lock.gen} and kept. Editing it makes it yours; the generator no longer applies.</p>
      )}
      {body.error && <p className="error">{body.error}</p>}

      <h3>Orbit</h3>
      <div className="field-row">
        <NumberField
          label={inKm ? 'Semi-major axis, km' : 'Semi-major axis, AU'}
          value={inKm ? v.orbit.a_km : v.orbit.a_au}
          onCommit={(a) => a !== undefined && a > 0 && setOrbit(inKm ? { a_km: a } : { a_au: a })}
          id="bodyA"
        />
        <label className="field">
          Unit
          <select
            value={inKm ? 'km' : 'au'}
            onChange={(e) => {
              const a = inKm ? v.orbit.a_km! : v.orbit.a_au!
              const AU_KM = 149_597_870.7
              const orbit = { ...v.orbit }
              delete orbit.a_au
              delete orbit.a_km
              if (e.target.value === 'km') orbit.a_km = inKm ? a : a * AU_KM
              else orbit.a_au = inKm ? a / AU_KM : a
              save({ orbit })
            }}
          >
            <option value="au">AU</option>
            <option value="km">km</option>
          </select>
        </label>
        <NumberField label="Eccentricity" value={v.orbit.e} onCommit={(e) => e !== undefined && setOrbit({ e })} />
        <NumberField label="Inclination, °" value={v.orbit.i_deg} onCommit={(i) => i !== undefined && setOrbit({ i_deg: i })} />
      </div>
      <div className="field-row">
        <NumberField
          label="Ascending node, °"
          value={v.orbit.node_deg}
          onCommit={(x) => x !== undefined && setOrbit({ node_deg: ((x % 360) + 360) % 360 })}
        />
        <NumberField
          label="Periapsis, °"
          value={v.orbit.peri_deg}
          onCommit={(x) => x !== undefined && setOrbit({ peri_deg: ((x % 360) + 360) % 360 })}
        />
        <NumberField
          label="Mean anomaly, °"
          value={v.orbit.meanAnomaly_deg}
          onCommit={(x) => x !== undefined && setOrbit({ meanAnomaly_deg: ((x % 360) + 360) % 360 })}
        />
      </div>
      <label className="field">
        …at
        <DateInput
          calendars={calendars}
          cal={v.orbit.epoch.cal ?? displayCal}
          text={v.orbit.epoch.text ?? epochText ?? ''}
          onCommit={(d) => setOrbit({ epoch: { t_s: d.t, cal: d.cal, text: d.text } })}
        />
      </label>

      <h3>Body</h3>
      <div className="field-row">
        <NumberField
          label="Mass, Earth masses"
          value={v.mass_mearth}
          onCommit={(m) => m !== undefined && m > 0 && save({ mass_mearth: m })}
        />
        <NumberField label="Radius, km" value={v.radius_km} onCommit={(r) => r !== undefined && r > 0 && save({ radius_km: r })} />
        <NumberField label="Albedo" value={v.albedo} optional placeholder="typical" onCommit={(albedo) => save({ albedo })} />
      </div>
      <div className="field-row">
        <label className="check">
          <input
            type="checkbox"
            checked={Boolean(v.rotation.locked)}
            onChange={(e) => setRotation(e.target.checked ? { locked: true } : { locked: undefined, period_h: 24 })}
          />
          Tidally locked
        </label>
        {!v.rotation.locked && (
          <NumberField
            label="Rotation, standard hours (negative: retrograde)"
            value={v.rotation.period_h}
            onCommit={(p) => p !== undefined && p !== 0 && setRotation({ period_h: p })}
          />
        )}
        <NumberField
          label="Axial tilt, °"
          value={v.rotation.tilt_deg}
          onCommit={(t) => t !== undefined && setRotation({ tilt_deg: Math.max(0, Math.min(180, t)) })}
        />
      </div>
      <details className="overrides">
        <summary>Orientation and air (for the sky view)</summary>
        <div className="field-row">
          <NumberField
            label="Spring equinox at orbital longitude, °"
            value={v.rotation.equinox_deg}
            optional
            placeholder="0"
            hint="From the orbit's ascending node."
            onCommit={(x) => setRotation({ equinox_deg: x === undefined ? undefined : ((x % 360) + 360) % 360 })}
          />
          {!v.rotation.locked && (
            <NumberField
              label="Prime meridian at time 0, °"
              value={v.rotation.meridian_deg}
              optional
              placeholder="0"
              hint="Turns the clock: where longitude 0 faces."
              onCommit={(x) => setRotation({ meridian_deg: x === undefined ? undefined : ((x % 360) + 360) % 360 })}
            />
          )}
        </div>
        <div className="field-row">
          <NumberField
            label="Surface pressure, atm"
            value={v.atmosphere?.pressure_atm}
            optional
            placeholder="no air"
            onCommit={(p) => save({ atmosphere: p === undefined ? undefined : { ...v.atmosphere, pressure_atm: Math.max(0, p) } })}
            id="bodyPressure"
          />
          {v.atmosphere && (
            <NumberField
              label="Scale height, km"
              value={v.atmosphere.scaleHeight_km}
              optional
              placeholder="8 km ÷ gravity"
              onCommit={(h) => save({ atmosphere: { ...v.atmosphere!, scaleHeight_km: h !== undefined && h > 0 ? h : undefined } })}
            />
          )}
        </div>
      </details>

      <h3>What follows</h3>
      <dl className="facts compact two-col">
        <dt>Orbital period</dt>
        <dd>{duration(body.period)}</dd>
        <dt>Year</dt>
        <dd>{duration(body.year)}</dd>
        <dt>Solar day</dt>
        <dd>{day !== null && !Number.isFinite(day) ? 'none: always the same face to the star' : duration(day)}</dd>
        <dt>Sunlight</dt>
        <dd>{body.insolation === null ? '—' : `${sig(body.insolation, 4)} W/m² (${sig(body.insolation / 1361, 3)} × Earth)`}</dd>
        <dt>Equilibrium temperature</dt>
        <dd>
          {body.equilibriumTemp === null
            ? '—'
            : `${sig(body.equilibriumTemp, 3)} K (${sig(body.equilibriumTemp - 273.15, 3)} °C), before any greenhouse`}
        </dd>
        <dt>Surface gravity</dt>
        <dd>{sig(body.surfaceGravity, 3)} g</dd>
        <dt>Escape velocity</dt>
        <dd>{sig(body.escapeVelocity / 1000, 3)} km/s</dd>
        <dt>Density</dt>
        <dd>{sig(body.density, 3)} g/cm³</dd>
        <dt>Hill sphere</dt>
        <dd>{body.hill === null ? '—' : `${sig(body.hill / 1000, 3)} km`}</dd>
        <dt>Foam collapse radius</dt>
        <dd>{body.collapse === null ? '—' : `${sig(body.collapse / 1000, 3)} km (${sig(body.collapse / 149_597_870_700, 3)} AU)`}</dd>
      </dl>
      {day !== null && Number.isFinite(day) && body.tilt > 0 && (
        <>
          <h3>Daylight through the year</h3>
          <table className="units daylight">
            <thead>
              <tr>
                <th>Latitude</th>
                <th>Longest day</th>
                <th>Shortest day</th>
              </tr>
            </thead>
            <tbody>
              {daylight.map((r) => (
                <tr key={r.lat}>
                  <td>{r.lat}°</td>
                  <td>{r.longest >= 1 ? 'all day' : duration(r.longest * day)}</td>
                  <td>{r.shortest <= 0 ? 'none' : duration(r.shortest * day)}</td>
                </tr>
              ))}
            </tbody>
          </table>
          <p className="muted small">
            The Sun's centre above the horizon, with an Earth-like atmosphere's refraction; the same in either hemisphere.
          </p>
        </>
      )}

      <div className="inspector-actions">
        <button className="danger" onClick={remove}>
          Delete…
        </button>
      </div>
      <p className="muted small">
        Saved as <code>{body.path}</code>
      </p>
    </div>
  )
}

function isDescendant(system: SystemInfoDto, id: string, ancestor: string): boolean {
  const byId = new Map(system.bodies.map((b) => [b.id, b]))
  let cur = byId.get(id)
  for (let guard = 0; cur && guard < 100; guard++) {
    if (cur.parent === ancestor) return true
    cur = cur.parent ? byId.get(cur.parent) : undefined
  }
  return false
}
